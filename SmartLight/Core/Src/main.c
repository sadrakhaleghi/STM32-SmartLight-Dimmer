/**
  * @brief  The application entry point.
  * @retval int
  */
int main(void)
{

  /* USER CODE BEGIN 1 */

  /* USER CODE END 1 */

  /* MCU Configuration--------------------------------------------------------*/

  /* Reset of all peripherals, Initializes the Flash interface and the Systick. */
  HAL_Init();

  /* USER CODE BEGIN Init */

  /* USER CODE END Init */

  /* Configure the system clock */
  SystemClock_Config();

  /* USER CODE BEGIN SysInit */

  /* USER CODE END SysInit */

  /* Initialize all configured peripherals */
  MX_GPIO_Init();
  MX_ADC1_Init();
  MX_TIM2_Init();
  MX_USART1_UART_Init();
  /* USER CODE BEGIN 2 */

  // --- بخش ضد‌ضربه (تنظیم زورکی تایمر) ---
  // این دو خط باعث می‌شود حتی اگر تنظیمات ioc خراب شد، اینجا درست شود
  __HAL_TIM_SET_PRESCALER(&htim2, 79);
  __HAL_TIM_SET_AUTORELOAD(&htim2, 99);

  // روشن کردن PWM
  HAL_TIM_PWM_Start(&htim2, TIM_CHANNEL_2);

  // پیام شروع
  HAL_UART_Transmit(&huart1, (uint8_t*)"System Ready! Turn Potentiometer...\r\n", 37, 100);

  /* USER CODE END 2 */

  /* Infinite loop */
  /* USER CODE BEGIN WHILE */
  while (1)
  {
    /* USER CODE END WHILE */

    /* USER CODE BEGIN 3 */
    if (system_off == 1)
    {
        // --- وضعیت خاموش ---
        __HAL_TIM_SET_COMPARE(&htim2, TIM_CHANNEL_2, 0);
    }
    else
    {
        // --- وضعیت روشن (دیمر) ---
        HAL_ADC_Start(&hadc1);
        HAL_ADC_PollForConversion(&hadc1, 10);
        adc_val = HAL_ADC_GetValue(&hadc1);

        // فرمول اصلاح شده (جلوگیری از باگ پرش نور)
        // ضربدر 99 می‌کنیم چون سقف تایمر ما الان 99 است
        uint32_t calc = (uint32_t)adc_val * 99;
        brightness = (uint8_t)(calc / 4095);

        __HAL_TIM_SET_COMPARE(&htim2, TIM_CHANNEL_2, brightness);
    }

    HAL_Delay(50); // کمی مکث برای ثبات
  }
  /* USER CODE END 3 */
}

